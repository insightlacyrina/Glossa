import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await build({
  entryPoints: [path.join(root, 'swift/Bridge/core.ts')],
  outfile: path.join(root, 'swift/Sources/GlossaCore/Resources/core.js'),
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  banner: {
    js: '// Generated by scripts/build-swift-core.mjs from the shared Glossa domain, review and export code.',
  },
});
console.log('Swift JavaScriptCore resource built from shared data kernel.');
